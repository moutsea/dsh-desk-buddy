import { decodeString } from "micromark-util-decode-string";
import type { Element, Parents, Root, Text } from "hast";
import type { Handle } from "mdast-util-from-markdown";
import type {} from "remark-parse";
import type { Processor } from "unified";

// Source positions come from the Markdown parser, before formatting removes
// delimiters. Runs keep ordinary text cheap while mapping escapes/entities.
export type SourceRun = [rendered: number, source: number];

// Share parser metadata between the remark and rehype stages for this file
// only. Weak keys avoid retaining completed renders or mixing documents.
const quotePrefixes = new WeakMap<object, Set<number>>();

export function remarkSourceAnchors(this: Processor) {
  const data = this.data();
  const rememberPrefix: Handle = function (token) {
    if (token.type !== "blockQuotePrefix") return;
    const root = this.stack[0];
    let offsets = quotePrefixes.get(root);
    if (!offsets) quotePrefixes.set(root, (offsets = new Set()));
    for (let offset = token.start.offset; offset < token.end.offset; offset++)
      offsets.add(offset);
  };
  (data.fromMarkdownExtensions ??= []).push({ beforeEnter: rememberPrefix });
  return (tree: object, file: object) => {
    const offsets = quotePrefixes.get(tree);
    if (offsets) quotePrefixes.set(file, offsets);
    else quotePrefixes.delete(file);
  };
}

function sourceRuns(
  source: string,
  node: Text,
  parent: Element | Root,
  codeBlock: boolean,
  quoteOffsets: ReadonlySet<number> | undefined,
  inTable: boolean,
) {
  const position = node.position || (codeBlock ? parent.position : undefined);
  let start = position?.start.offset;
  const end = position?.end.offset;
  if (start === undefined || end === undefined || !node.value) return;
  let raw = source.slice(start, end);
  const code = parent.type === "element" && parent.tagName === "code";
  if (code) {
    const opening = codeBlock
      ? /^(?: {0,3})(?:`{3,}|~{3,})[^\r\n]*(?:\r\n|\r|\n)/.exec(raw)?.[0]
      : /^`+/.exec(raw)?.[0];
    if (opening) {
      start += opening.length;
      raw = raw.slice(opening.length);
    }
  }
  // Most text has a direct source mapping. Avoid per-character allocations
  // for the common case, especially while a long reply is still growing.
  if (raw === node.value || (code && raw.startsWith(node.value)))
    return {
      runs: [[0, start]] as SourceRun[],
      end: start + node.value.length,
    };
  const units: { value: string; offset: number }[] = [];
  const token =
    /\\[!-/:-@[-`{-~]|&(?:#(?:\d{1,7}|x[\da-f]{1,6})|[\da-z]{1,31});|\r\n|[\s\S]/gi;
  for (const match of raw.matchAll(token)) {
    // The parser distinguishes actual prefixes from literal '>' even when
    // container indentation or optional quote spacing changes between lines.
    if (quoteOffsets?.has(start + match.index!)) continue;
    const rawText = match[0];
    // Inline code turns line endings into spaces; other Markdown normalizes
    // CRLF to LF. Code keeps literal backslashes and entity spellings, except
    // that GFM table cells unescape pipes inside inline code. The tokenizer
    // keeps escaped backslash pairs intact, matching GFM's escape precedence.
    const value = code
      ? inTable && !codeBlock && rawText === "\\|"
        ? "|"
        : rawText.replace(/\r\n|\r|\n/g, codeBlock ? "\n" : " ")
      : decodeString(rawText).replace(/\r\n|\r/g, "\n");
    for (let i = 0; i < value.length; i++)
      units.push({
        value: value[i],
        offset: start + match.index! + (rawText === value ? i : 0),
      });
  }
  const runs: SourceRun[] = [];
  let cursor = 0,
    previous = -2;
  for (let i = 0; i < node.value.length; i++) {
    // HAST trims line indentation. Skip only parser-discarded whitespace;
    // an unmappable transformation gets no character anchor.
    while (
      cursor < units.length &&
      units[cursor].value !== node.value[i] &&
      /\s/.test(units[cursor].value)
    )
      cursor++;
    if (units[cursor]?.value !== node.value[i]) {
      // Fenced code's final LF is generated by the renderer.
      if (codeBlock && i === node.value.length - 1 && node.value[i] === "\n")
        break;
      return;
    }
    const offset = units[cursor++].offset;
    if (offset !== previous + 1) runs.push([i, offset]);
    previous = offset;
  }
  return runs.length ? { runs, end: previous + 1 } : undefined;
}

export function rehypeSourceAnchors() {
  return (tree: Root, file: { value: unknown }) => {
    const source = String(file.value);
    const quoteOffsets = quotePrefixes.get(file);
    const visit = (parent: Parents, grandparent?: Parents, inTable = false) => {
      if (parent.type === "element" && parent.tagName === "table")
        inTable = true;
      parent.children = parent.children.map((child) => {
        if (child.type === "element") {
          visit(child, parent, inTable);
        } else if (child.type === "text") {
          const mapping = sourceRuns(
            source,
            child,
            parent as Element | Root,
            parent.type === "element" &&
              parent.tagName === "code" &&
              grandparent?.type === "element" &&
              grandparent.tagName === "pre",
            quoteOffsets,
            inTable,
          );
          if (mapping)
            return {
              type: "element",
              tagName: "span",
              properties: {
                "data-source-start": mapping.runs[0][1],
                "data-source-end": mapping.end,
                ...(mapping.runs.length > 1
                  ? { "data-source-runs": JSON.stringify(mapping.runs) }
                  : {}),
              },
              children: [child],
            } as Element;
        }
        return child;
      });
    };
    visit(tree);
  };
}
